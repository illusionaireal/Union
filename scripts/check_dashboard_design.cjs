/* Design prototype checks. No organization database, model or deployment access. */
const {chromium} = require(process.env.UNION_PLAYWRIGHT_MODULE || "playwright-core");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname,"..");
const output = path.join(root,"evidence/design");

(async()=>{
  const browser = await chromium.launch({headless:true,executablePath:process.env.UNION_CHROMIUM_PATH || "/usr/bin/chromium"});
  const checks=[],errors=[],requests=[];
  const check=(name,value)=>{assert.ok(value,name);checks.push(name);};
  fs.mkdirSync(output,{recursive:true});
  try{
    const context=await browser.newContext({viewport:{width:1440,height:1100},reducedMotion:"reduce"});
    await context.setOffline(true);
    const page=await context.newPage();
    page.on("pageerror",error=>errors.push(error.message));
    page.on("console",message=>{if(message.type()==="error")errors.push(message.text());});
    page.on("request",request=>requests.push(request.url()));
    await page.route("**/*",route=>route.abort());
    await page.setContent(fs.readFileSync(path.join(root,"ai-union-dashboard-prototype.html"),"utf8"),{waitUntil:"load"});
    await page.waitForFunction(()=>window.UNION_DESIGN_STATE);
    const nav=async key=>{await page.locator(`#navigation [data-key="${key}"]`).click();};
    const scenario=async key=>{await page.locator("#scenario").selectOption(key);};
    check("prototype clearly labels all data as simulation",await page.getByText("全部为模拟情景 · 未接入组织服务",{exact:true}).count()===1);
    check("seven design views available",await page.locator(".nav-button").count()===7);
    check("active execution scenario is not labelled needs review",(await page.locator(".status-hero").textContent()).includes("协作进行中") && await page.locator('[data-task="work-two"] .badge').textContent()==="执行中 · 模拟");
    check("one delivered artifact in collaboration scenario",await page.locator(".artifact-row").count()===1);
    await page.screenshot({path:path.join(output,"overview-desktop.png"),fullPage:true});
    await page.locator('[data-task="work-two"] .task-name').click();
    check("work detail includes responsibility and dependency",await page.locator("#detail-dialog").isVisible() && (await page.locator("#detail-body").textContent()).includes("测试成员 B"));
    await page.locator('#detail-body [data-action="task"][data-id="work-one"]').click();
    check("dependency opens actual previous work detail",await page.locator("#detail-title").textContent()==="生成模拟资料");
    await page.locator('#detail-body [data-action="artifact"][data-id="0"]').click();
    check("artifact preview matches embedded public fixture",(await page.locator("#artifact-text").textContent()).includes("模拟资料"));
    const pending=page.waitForEvent("download");
    await page.locator("#download-artifact").click();
    const download=await pending;
    const stream=await download.createReadStream();const chunks=[];for await(const chunk of stream)chunks.push(chunk);
    check("artifact actually downloads with exact content",await download.failure()===null && download.suggestedFilename()==="source.md" && Buffer.concat(chunks).toString("utf8")===await page.locator("#artifact-text").textContent());
    await page.keyboard.press("Escape");
    check("escape closes detail dialog",!(await page.locator("#detail-dialog").isVisible()));
    await nav("members");
    check("member view shows two distinct fixture identities",await page.locator(".member-card").count()===2);
    await page.locator('.member-card [data-id="fixture-two"]').click();
    check("member detail contains responsible task",await page.locator('#detail-body [data-id="work-two"]').count()===1);
    await page.locator('#detail-body [data-id="work-two"]').click();
    check("member to task navigation works",(await page.locator("#detail-title").textContent())==="使用依赖成果");
    await page.locator("#close-dialog").click();
    await nav("tasks");
    await page.locator("#task-filter").selectOption("delivered");
    check("status filter reduces work list",await page.locator(".task-table tbody tr").count()===1);
    await page.locator("#member-filter").selectOption("B");
    check("combined member and status filters show empty result",await page.getByText("没有匹配的工作",{exact:true}).isVisible());
    await page.getByRole("button",{name:"清空筛选",exact:true}).click();
    check("clear filters restores work list",await page.locator(".task-table tbody tr").count()===2);
    await page.locator("#task-search").fill("work-two");
    check("search matches task identifier",await page.locator(".task-table tbody tr").count()===1 && await page.locator('[data-task="work-two"]').count()===1);
    await scenario("waiting");await nav("artifacts");
    check("completed scenario exposes three public artifacts",await page.locator(".artifact-card").count()===3);
    await page.locator('.artifact-card [data-id="2"]').click();
    check("followup artifact is readable",(await page.locator("#artifact-text").textContent()).includes("模拟后续动作"));
    await page.keyboard.press("Escape");
    await scenario("unavailable");await nav("artifacts");
    await page.locator('.artifact-card [data-id="0"]').click();
    check("unavailable artifact preserves provenance and prevents download",await page.locator("#download-artifact").isDisabled() && await page.locator("#artifact-text").count()===0 && (await page.locator("#detail-body").textContent()).includes("历史交付记录保留"));
    await page.keyboard.press("Escape");await scenario("waiting");
    await nav("activity");await page.locator('[data-action="activity-filter"][data-key="decision"]').click();
    check("decision type filter shows bounded timeline",await page.locator(".timeline-item").count()===3);
    await page.locator('[data-action="activity-filter"][data-key="all"]').click();
    await page.locator('[data-action="more-events"]').click();
    check("show more renders remaining design activity",await page.locator(".timeline-item").count()===6 && await page.locator('[data-action="more-events"]').isDisabled());
    await nav("resources");
    check("unknown cost and missing token receipts stay explicit",(await page.locator(".receipt-values").textContent()).includes("未知") && (await page.locator(".receipt-values").textContent()).includes("未提供"));
    check("resource view displays six fixture calls and zero real model calls",await page.locator(".run-row").count()===6 && (await page.locator(".receipt-values").textContent()).includes("0 次"));
    for(const [key,label] of [["unknown","执行待核对"],["unconfirmed","活性未确认"],["budget","额度已用尽"],["empty","组织尚未形成"],["rejected","决定被拒绝"]]){
      await scenario(key);await nav("overview");check("scenario: "+key,(await page.locator(".status-hero").textContent()).includes(label));
    }
    await nav("activity");await page.locator('[data-action="activity-filter"][data-key="decision"]').click();
    check("rejected decision retains refusal reason",(await page.locator(".timeline").textContent()).includes("原因：决定版本冲突"));
    await scenario("working");await nav("overview");
    const before=await page.evaluate(()=>({...window.UNION_DESIGN_STATE}));
    await scenario("disconnected");
    check("disconnect marks retained snapshot as stale",await page.locator("#connection-warning").isVisible() && (await page.locator("#connection-label").textContent()).includes("断开"));
    await page.locator("#refresh").click();
    check("refresh during disconnected scenario does not fabricate reconnect",(await page.evaluate(()=>window.UNION_DESIGN_STATE)).connected===false && (await page.evaluate(()=>window.UNION_DESIGN_STATE)).sequence===before.sequence);
    await page.screenshot({path:path.join(output,"disconnected-desktop.png"),fullPage:true});
    await scenario("working");
    check("scenario recovery clears stale warning",!(await page.locator("#connection-warning").isVisible()));
    check("scenario recovery clears obsolete disconnect toast",!(await page.locator("#toast").isVisible()));
    await page.locator(".design-tools summary").first().click();
    const previous=await page.evaluate(()=>({...window.UNION_DESIGN_STATE}));
    await page.locator("#same-version").click();
    const newer=await page.evaluate(()=>({...window.UNION_DESIGN_STATE}));
    check("simulated event updates independently of state version",newer.version===previous.version && newer.sequence>previous.sequence && newer.pending_events===previous.pending_events+1);
    await nav("activity");await page.locator('[data-action="activity-filter"][data-key="event"]').click();
    check("new event visible in timeline",(await page.locator(".timeline").textContent()).includes("同版本新增模拟事件"));
    const oldBefore=await page.evaluate(()=>JSON.stringify(window.UNION_DESIGN_STATE));
    const timeBefore=await page.locator("#last-updated").textContent();
    await page.locator("#old-response").click();
    check("old simulated response is actually rejected by sequence guard",await page.evaluate(()=>JSON.stringify(window.UNION_DESIGN_STATE))===oldBefore && await page.locator("#last-updated").textContent()===timeBefore && (await page.locator("#tool-feedback").textContent()).includes("已丢弃"));
    await page.locator("#reset-design").click();
    check("design reset restores original scenario",(await page.evaluate(()=>window.UNION_DESIGN_STATE)).scenario==="working" && (await page.evaluate(()=>window.UNION_DESIGN_STATE)).pending_events===0);
    await page.locator('#navigation [data-key="tasks"]').focus();await page.keyboard.press("Enter");
    check("navigation works with keyboard",await page.locator("#page-title").textContent()==="工作与依赖");
    await page.locator('[data-task="work-two"] .task-name').focus();await page.keyboard.press("Enter");
    check("task detail works with keyboard",await page.locator("#detail-dialog").isVisible());
    await page.keyboard.press("Escape");
    check("dialog returns focus to original task trigger",await page.locator('[data-task="work-two"] .task-name').evaluate(element=>element===document.activeElement));
    await nav("overview");
    for(const width of [1440,1024,390,320]){
      await page.setViewportSize({width,height:950});
      check("no body overflow at "+width,await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
      if(width===390)await page.screenshot({path:path.join(output,"overview-mobile.png"),fullPage:true});
    }
    await page.setViewportSize({width:390,height:950});await nav("tasks");
    await page.locator('[data-task="work-two"] .task-name').click();
    check("mobile task dialog fits viewport",await page.locator("#detail-dialog").evaluate(element=>element.getBoundingClientRect().right<=window.innerWidth && element.getBoundingClientRect().left>=0));
    await page.screenshot({path:path.join(output,"task-mobile.png"),fullPage:true});
    check("no external resources",await page.locator("script[src], link[rel=stylesheet]").count()===0);
    check("offline design interactions make zero network requests",requests.length===0);
    check("no script or CSP errors",errors.length===0);
    fs.writeFileSync(path.join(output,"browser-validation.json"),JSON.stringify({status:"passed",checked_at:new Date().toISOString(),mode:"offline browser document (setContent)",browser:await browser.version(),scope:"design prototype only; no runtime data service validation",checks,errors,requests,real_model_calls:0,direct_file_navigation_verified:false},null,2));
    console.log(`${checks.length} design browser checks passed; screenshots saved`);
  }catch(error){fs.writeFileSync(path.join(output,"browser-validation.json"),JSON.stringify({status:"failed",checks,error:error.message,errors,requests},null,2));throw error;}finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
